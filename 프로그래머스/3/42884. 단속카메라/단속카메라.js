// 차량이 나가기 전까지 반드시 하나의 카메라를 지나야함
// 그리디를 사용할 수 있는 이유 => 차를 검문하기 위해 늦게 설치할 수 있는 위치를 선택하는 것이 가장 적은 카메라를 설치하는 경우


// 정렬: 차량의 나가는 지점(routes[i][1])을 기준으로 오름차순 정렬
// 카메라 설치: 첫 번째 차량이 나가는 지점에 무조건 카메라를 하나 설치
// 비교: 다음 차량의 진입 지점이 현재 설치된 카메라의 위치보다 뒤에 있다면(즉, 카메라를 만나지 못한다면), 그 차량이 나가는 지점에 새로운 카메라를 설치
// 반복: 모든 차량을 확인할 때까지 이 과정을 반복

function solution(routes) {
    // 1. 차량의 나가는 지점(routes[i][1])을 기준으로 오름차순 정렬
    // 나가는 지점이 빠른 순서대로 처리해야 다음 차량들과의 겹침을 최소한의 카메라로 확인 가능
    routes.sort((a, b) => a[1] - b[1]);

    let cameras = 0; // 설치된 카메라 대수
    let lastCamera = -30001; // 마지막으로 설치된 카메라의 위치 (문제 범위 밖으로 초기화)

    for (let i = 0; i < routes.length; i++) {
        const [start, end] = routes[i];

        // 2. 현재 차량의 진입 지점이 마지막 카메라 위치보다 뒤에 있는지 확인
        // 만약 진입 지점이 lastCamera보다 크다면, 현재 차량은 기존 카메라를 만나지 못함
        if (start > lastCamera) {
            // 3. 새로운 카메라를 이 차량의 '나가는 지점'에 설치
            // 진출 지점에 설치해야 그다음 차량들과 겹칠 확률이 가장 높기 때문(Greedy)
            cameras++;
            lastCamera = end;
        }
        
        // 만약 start <= lastCamera 라면, 이미 기존 카메라 범위에 포함되므로 
        // 추가 설치 없이 다음 차량으로 넘어감
    }

    return cameras;
}