def solution(h1, m1, s1, h2, m2, s2):
    # 0시 0분 0초(초과)부터 특정 초(T)까지 알람이 울린 횟수를 계산하는 함수
    def get_count(time_in_sec):
        # 초침과 시침 겹침 (12시간 동안 719번 추월)
        h_match = (time_in_sec * 719) // 43200
        # 초침과 분침 겹침 (1시간 단위로 59번 추월)
        m_match = (time_in_sec * 59) // 3600
        # 12시 정각(43,200초)에 시/분/초침이 모두 겹치므로 중복 계산된 1회 차감
        penalty = time_in_sec // 43200
        
        return h_match + m_match - penalty

    # 시간을 모두 '초'로 변환
    t1 = h1 * 3600 + m1 * 60 + s1
    t2 = h2 * 3600 + m2 * 60 + s2

    # (0초 ~ t2초 알람 횟수) - (0초 ~ t1초 알람 횟수)
    result = get_count(t2) - get_count(t1)

    # 시작 시간(t1)에 대한 엣지 케이스 보정
    # 초침이 분침/시침과 '정수 초'에 오차 없이 완벽히 겹치는 순간은 매시간 정각(00분 00초) 뿐입니다.
    # get_count(t)는 구간 (0, t]를 의미하므로, 시작 시간(t1) 자체에 울리는 알람이 제외되어 있습니다.
    # 따라서 시작 시간이 정각이라면 1번 울린 것을 더해줍니다. (0시, 12시 정각도 포함됨)
    if t1 % 3600 == 0:
        result += 1

    return result