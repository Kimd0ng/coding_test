// 이 문제를 보면 한번에 2명밖에 타지 못하는 배
// 배의 최대 제한 무계가 정해져 있음
// 배에 탈 사람 한명을 골랐을때 -> 한명과 더 탈 수 있는지 없는지 판단

// 60 40 50 50
// 60 40 / 50 50
// 50 40 / 60 / 50

// 무작위의 선택은 최선의 선택이 아닐수가 있음
// 최선의 선택을 하기 위해서는 누가 혼자 타는지 확인
    // 누가 혼자타냐, 가장 가벼운 사람과 함게 타지 못하는 무거운 사람만 혼자탐
    // 지금 있는 사람들중 가벼운 사람 찾고, 무거운 사람 찾아서
    // 되면 => 둘이 함께
    // 안되면 => 무거운 사람만 혼자


/**
 * [문제 분석]
 * 1. 한 배에 최대 2명까지만 탑승 가능 (중요 제약)
 * 2. 무게 제한(limit) 존재
 * 3. 목표: 최소한의 보트 개수 사용
 * * [풀이 전략: Greedy & Two Pointer]
 * - 사람들을 몸무게순으로 정렬한다.
 * - 가장 무거운 사람(Right)을 먼저 태운다고 가정할 때, 
 * 남은 사람 중 가장 가벼운 사람(Left)이 같이 탈 수 있는지 확인한다.
 * - 된다면 둘 다 보트에서 제거, 안 된다면 무거운 사람만 혼자 보낸다.
 */

function solution(people, limit) {
    let answer = 0;
    // 1. 오름차순 정렬 (가벼운 사람 -> 무거운 사람)
    people.sort((a, b) => a - b);
    
    let left = 0;              // 가장 가벼운 사람의 인덱스
    let right = people.length - 1; // 가장 무거운 사람의 인덱스
    
    // 두 포인터가 만날 때까지 반복
    while (left <= right) {
        // 가장 무거운 사람 + 가장 가벼운 사람의 합이 limit 이하인가?
        if (people[left] + people[right] <= limit) {
            // 같이 탈 수 있다면 가벼운 사람도 다음 순서로 넘김
            left++;
        }
        // 무거운 사람은 (같이 타든 혼자 타든) 무조건 이번 보트에 탐
        right--;
        
        // 보트 한 대 사용 완료
        answer++;
    }
    
    return answer;
}